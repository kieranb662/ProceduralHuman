import { defineHuman, type HumanDesign } from "../../humans/design.js";

export const PACKAGE_NAME = "@kieranb662/procedural-human";

export interface HumanModuleOptions {
  /** "js" (default) emits an ES module with JSDoc types; "ts" emits TypeScript. */
  language?: "js" | "ts";
  /**
   * Where the module imports from. Defaults to the published package.
   * Pass separate specifiers to import from source files (used for bundled presets).
   */
  importFrom?: string | { defineHuman: string; createHuman: string };
}

/** "Default Adult Male" -> "defaultAdultMale" (always a valid JS identifier). */
export function humanIdentifier(name: string): string {
  const words = name.replace(/[^A-Za-z0-9]+/g, " ").trim().split(" ").filter(Boolean);
  const id = words.map((w, i) => (i === 0 ? w[0].toLowerCase() : w[0].toUpperCase()) + w.slice(1)).join("");
  return /^[A-Za-z_$]/.test(id) ? id : `human${id ? id[0].toUpperCase() + id.slice(1) : ""}`;
}

/** "Default Adult Male" -> "default-adult-male". */
export function humanFileStem(name: string): string {
  return name.replace(/[^A-Za-z0-9]+/g, "-").replace(/^-|-$/g, "").toLowerCase() || "human";
}

/** Suggested file name for a generated module, e.g. "default-adult-male.human.js". */
export function humanModuleFileName(design: HumanDesign, language: "js" | "ts" = "js"): string {
  return `${humanFileStem(design.name)}.human.${language}`;
}

/** The design as pretty-printed JSON (also a valid JS/TS object literal). */
export function serializeHumanDesign(design: HumanDesign): string {
  return JSON.stringify(defineHuman(design), null, 2);
}

/**
 * Emits a self-contained ES module that rebuilds this exact human in any project that has
 * `@kieranb662/procedural-human` and `three` installed. Exports the design data, a
 * `create<Name>()` factory, and the design as the default export.
 */
export function generateHumanModule(design: HumanDesign, options: HumanModuleOptions = {}): string {
  const language = options.language ?? "js";
  const full = defineHuman(design);
  const id = humanIdentifier(full.name);
  const factory = `create${id[0].toUpperCase()}${id.slice(1)}`;
  const from = options.importFrom ?? PACKAGE_NAME;
  const ts = language === "ts";

  const imports = typeof from === "string"
    ? [`import { createHuman, defineHuman${ts ? ", type CreateHumanOptions" : ""} } from ${JSON.stringify(from)};`]
    : [
      `import { createHuman${ts ? ", type CreateHumanOptions" : ""} } from ${JSON.stringify(from.createHuman)};`,
      `import { defineHuman } from ${JSON.stringify(from.defineHuman)};`,
    ];
  const typesFrom = typeof from === "string" ? from : from.createHuman;

  return [
    `// ${full.name}: procedural human generated by ${PACKAGE_NAME}.`,
    `// Requires: npm install ${PACKAGE_NAME} three`,
    `//`,
    `// Usage:`,
    `//   import { ${factory} } from "./${humanFileStem(full.name)}.human.js";`,
    `//   const human = ${factory}();`,
    `//   scene.add(human.root);`,
    `//   renderer.setAnimationLoop(() => human.update(clock.getDelta()));`,
    ...imports,
    ``,
    `export const ${id} = defineHuman(${serializeHumanDesign(full)});`,
    ``,
    `/** Builds a new, independently animated instance of ${full.name.replace(/\*\//g, "")}. */`,
    ts
      ? `export function ${factory}(options?: CreateHumanOptions) {`
      : `/** @param {import(${JSON.stringify(typesFrom)}).CreateHumanOptions} [options] */\nexport function ${factory}(options) {`,
    `  return createHuman(${id}, options);`,
    `}`,
    ``,
    `export default ${id};`,
    ``,
  ].join("\n");
}
